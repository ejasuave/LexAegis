/**
 * Writes (or with --check, verifies) contracts/REGISTRY_REFERENCE.md: a reference for the
 * `IProofOfReviewRegistry` interface generated from the compiled interface and the committed
 * artifact. The interface source and the registry are frozen, so the EIP-712 typed-data
 * definitions and domain live here instead of in new NatSpec. Nothing here is written by hand:
 * values come from compiler output and contracts/artifacts/registry-v1.json.
 *
 *   pnpm contracts:reference         write the file
 *   pnpm contracts:reference:check   fail if it is stale (also run by contracts:artifacts:check users)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { toEventSelector, toFunctionSelector } from 'viem';
import { contractsDir } from './lib/toolchain';

interface Param {
  name: string;
  type: string;
  indexed?: boolean;
  components?: Param[];
}
interface Item {
  type: string;
  name?: string;
  inputs?: Param[];
  outputs?: Param[];
  stateMutability?: string;
}

const interfaceOut = join(
  contractsDir,
  'out',
  'IProofOfReviewRegistry.sol',
  'IProofOfReviewRegistry.json',
);
if (!existsSync(interfaceOut)) {
  console.error('the compiled interface is missing: run pnpm contracts:build first');
  process.exit(2);
}
const abi = (JSON.parse(readFileSync(interfaceOut, 'utf8')) as { abi: Item[] }).abi;
const artifact = JSON.parse(
  readFileSync(join(contractsDir, 'artifacts', 'registry-v1.json'), 'utf8'),
) as {
  protocolVersion: string;
  actionCodes: Record<string, number>;
  receiptStatus: string[];
  supersessionEventOrder: string[];
  eip712: {
    domain: { name: string; version: string };
    domainTypeString: string;
    primaryType: string;
    typeString: string;
    typeHash: string;
    fields: { name: string; type: string }[];
  };
  compiler: Record<string, unknown>;
  dependencies: Record<string, string>;
};

const TICK = '`';
const typeOf = (param: Param): string =>
  param.type.startsWith('tuple')
    ? `(${(param.components ?? []).map(typeOf).join(',')})${param.type.slice('tuple'.length)}`
    : param.type;
const sig = (item: Item): string =>
  `${item.name ?? ''}(${(item.inputs ?? []).map(typeOf).join(',')})`;
const outputs = (item: Item): string =>
  (item.outputs ?? []).length === 0
    ? ''
    : ` returns (${(item.outputs ?? []).map(typeOf).join(', ')})`;

const lines: string[] = [
  '# Proof of Review registry v1: interface reference',
  '',
  'Generated by `pnpm contracts:reference` from the compiled `IProofOfReviewRegistry` and',
  '`contracts/artifacts/registry-v1.json`. Do not edit. The registry and the interface are frozen at',
  `protocol version ${artifact.protocolVersion}; this file describes them and changes nothing.`,
  '',
  `Build: ${JSON.stringify(artifact.compiler)}. Libraries: ${Object.entries(artifact.dependencies)
    .map(([name, version]) => `${name} ${version}`)
    .join(', ')}.`,
  '',
  '## Functions',
  '',
  '| Selector | Signature | Mutability |',
  '| --- | --- | --- |',
  ...abi
    .filter((item) => item.type === 'function')
    .map(
      (item) =>
        `| \`${toFunctionSelector(sig(item))}\` | \`${sig(item)}${outputs(item)}\` | ${item.stateMutability ?? ''} |`,
    ),
  '',
  '## Events',
  '',
  '| Topic 0 | Signature | Indexed |',
  '| --- | --- | --- |',
  ...abi
    .filter((item) => item.type === 'event')
    .map(
      (item) =>
        `| \`${toEventSelector(sig(item))}\` | \`${sig(item)}\` | ${(item.inputs ?? [])
          .filter((input) => input.indexed === true)
          .map((input) => input.name)
          .join(', ')} |`,
    ),
  '',
  `A SUPERSEDE emits ${artifact.supersessionEventOrder.map((name) => `${TICK}${name}${TICK}`).join(' then ')} in one transaction with the same nonce.`,
  '',
  '## Errors',
  '',
  '| Selector | Signature |',
  '| --- | --- |',
  ...abi
    .filter((item) => item.type === 'error')
    .map((item) => `| \`${toFunctionSelector(sig(item))}\` | \`${sig(item)}\` |`),
  '',
  '## Receipt status (enum order is part of the v1 ABI)',
  '',
  ...artifact.receiptStatus.map((name, index) => `- \`${String(index)}\` ${name}`),
  '',
  '## Action codes (`ReviewAction.action`)',
  '',
  ...Object.entries(artifact.actionCodes).map(([name, code]) => `- \`${String(code)}\` ${name}`),
  '',
  '## EIP-712 typed data a reviewer signs',
  '',
  `Domain: name \`${artifact.eip712.domain.name}\`, version \`${artifact.eip712.domain.version}\`, \`chainId\` and \`verifyingContract\` of the registry.`,
  '',
  '```text',
  artifact.eip712.domainTypeString,
  artifact.eip712.typeString,
  `typeHash ${artifact.eip712.typeHash}`,
  '```',
  '',
  '```json',
  JSON.stringify(
    {
      primaryType: artifact.eip712.primaryType,
      types: {
        EIP712Domain: [
          { name: 'name', type: 'string' },
          { name: 'version', type: 'string' },
          { name: 'chainId', type: 'uint256' },
          { name: 'verifyingContract', type: 'address' },
        ],
        [artifact.eip712.primaryType]: artifact.eip712.fields,
      },
    },
    null,
    2,
  ),
  '```',
  '',
  "The nonce is the reviewer's registry counter (`nonceOf`), shared by every action; `deadline` is the",
  'last Unix second at which the action may execute. EIP-712 binds a signature to a chain and a registry:',
  'only the stored nonce stops reuse. `msg.sender` is the executor, never the reviewer. Literal digests',
  'and signatures for seven actions are in `fixtures/registry-v1/vectors.json`; the specification is',
  '`docs/SPEC.md`.',
  '',
];
const expected = `${lines.join('\n')}\n`;
const path = join(contractsDir, 'REGISTRY_REFERENCE.md');
if (process.argv.includes('--check')) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current !== expected) {
    console.error('contracts/REGISTRY_REFERENCE.md is stale: run pnpm contracts:reference');
    process.exit(1);
  }
  console.log('registry reference is current');
} else {
  writeFileSync(path, expected);
  console.log('wrote contracts/REGISTRY_REFERENCE.md');
}
