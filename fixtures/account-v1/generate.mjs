/**
 * Fixture-generation utility for the account derivation profile `lexaegis.evm.bip32-prf.v1`.
 *
 * INDEPENDENCE RULE: never imports @lexaegis/*, packages/, apps/, contracts/ or viem. Each
 * address is derived twice and the two must agree before anything is written: once with the
 * @scure/bip32 library, and once with BIP-32 private derivation written out below from the
 * specification (HMAC-SHA512 from node:crypto, scalar arithmetic in BigInt).
 *
 *   node fixtures/account-v1/generate.mjs          write vectors.json
 *   node fixtures/account-v1/generate.mjs --check  fail if vectors.json is not reproducible
 *
 * Everything here is SYNTHETIC. The inputs stand in for a passkey PRF output; no real user's
 * PRF output or key ever appears in a fixture.
 */
import { Buffer } from 'node:buffer';
import { createHash, createHmac } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { secp256k1 } from '@noble/curves/secp256k1';
import { keccak_256 } from '@noble/hashes/sha3';
import { HDKey } from '@scure/bip32';

const PROFILE_ID = 'lexaegis.evm.bip32-prf.v1';
const EVM_PATH = "m/44'/60'/0'/0/0";
const SALT_LABELS = { account: 'lexaegis:account:evm:v1', vault: 'lexaegis:vault:root:v1' };

const N = 0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141n;
const HARDENED = 0x80000000;
const hex = (bytes) => `0x${Buffer.from(bytes).toString('hex')}`;
const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest();
const hmac512 = (key, data) => createHmac('sha512', key).update(data).digest();
const toScalar = (bytes) => BigInt(`0x${Buffer.from(bytes).toString('hex')}`);
const fromScalar = (value) => Buffer.from(value.toString(16).padStart(64, '0'), 'hex');

function ser32(index) {
  const out = Buffer.alloc(4);
  out.writeUInt32BE(index);
  return out;
}

/** BIP-32 CKDpriv along a path, from the specification. */
function deriveByHand(seed, path) {
  let I = hmac512(Buffer.from('Bitcoin seed', 'utf8'), seed);
  let key = toScalar(I.subarray(0, 32));
  let chain = I.subarray(32);
  for (const part of path.split('/').slice(1)) {
    const hardened = part.endsWith("'");
    const index = Number.parseInt(part, 10) + (hardened ? HARDENED : 0);
    const data = hardened
      ? Buffer.concat([Buffer.from([0]), fromScalar(key), ser32(index)])
      : Buffer.concat([Buffer.from(secp256k1.getPublicKey(fromScalar(key), true)), ser32(index)]);
    I = hmac512(chain, data);
    const tweak = toScalar(I.subarray(0, 32));
    if (tweak >= N) throw new Error('invalid child (tweak out of range)');
    key = (tweak + key) % N;
    if (key === 0n) throw new Error('invalid child (zero key)');
    chain = I.subarray(32);
  }
  return fromScalar(key);
}

function addressOf(privateKey) {
  const publicKey = secp256k1.getPublicKey(privateKey, false);
  return hex(Buffer.from(keccak_256(publicKey.subarray(1))).subarray(12));
}

function derive(seed, path) {
  const library = HDKey.fromMasterSeed(seed).derive(path).privateKey;
  const manual = deriveByHand(seed, path);
  if (library === null || !Buffer.from(library).equals(manual)) {
    throw new Error('independent BIP-32 derivations disagree');
  }
  return addressOf(manual);
}

const inputs = [
  ['sequence', 'Bytes 0x00..0x1f', Buffer.from(Array.from({ length: 32 }, (_, index) => index))],
  ['repeated', '0x11 repeated', Buffer.alloc(32, 0x11)],
  ['label-hash', 'SHA-256 of a synthetic label', sha256('SYNTHETIC account-v1 PRF output A')],
  ['high-bytes', '0xff repeated', Buffer.alloc(32, 0xff)],
];

const vectors = {
  $comment:
    'SYNTHETIC account derivation vectors. Generated by fixtures/account-v1/generate.mjs, independently of the application. prfOutput values stand in for a passkey PRF output; none is a real secret. Do not edit by hand.',
  format: 'lexaegis.account-v1.test-vectors/1',
  profileId: PROFILE_ID,
  path: EVM_PATH,
  salts: Object.fromEntries(
    Object.entries(SALT_LABELS).map(([name, label]) => [
      name,
      { label, sha256: hex(sha256(label)) },
    ]),
  ),
  cases: inputs.map(([id, description, seed]) => ({
    id,
    description,
    prfOutput: hex(seed),
    address: derive(seed, EVM_PATH),
    // The same input on the next path: a different account, so a path change is never silent.
    addressAtNextIndex: derive(seed, "m/44'/60'/0'/0/1"),
  })),
};

const path = join(dirname(fileURLToPath(import.meta.url)), 'vectors.json');
const output = `${JSON.stringify(vectors, null, 2)}\n`;

function readOrNull(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}

if (process.argv.includes('--check')) {
  if (readOrNull(path) !== output) {
    console.error('fixtures/account-v1/vectors.json is not reproducible from generate.mjs');
    process.exit(1);
  }
  console.log('fixtures/account-v1/vectors.json is reproducible');
} else {
  writeFileSync(path, output);
  console.log(`wrote ${vectors.cases.length} cases to fixtures/account-v1/vectors.json`);
}
