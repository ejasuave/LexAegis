/**
 * Fixture-generation utility for the vault crypto profile
 * `lexaegis.vault.hkdf-sha256.aes-256-gcm.v1`.
 *
 * INDEPENDENCE RULE: never imports @lexaegis/*, packages/, apps/, contracts/ or viem, and does
 * not use Web Crypto. HKDF-SHA256 and AES-256-GCM come from node:crypto (OpenSSL), JCS from the
 * separately authored json-canonicalize library, and base64url from Buffer. The application
 * implementation must reproduce every byte below through the browser's Web Crypto.
 *
 *   node fixtures/vault-v1/generate.mjs          write vectors.json
 *   node fixtures/vault-v1/generate.mjs --check  fail if vectors.json is not reproducible
 *
 * Everything is SYNTHETIC. The PRF outputs, salts and IVs are FIXED for reproducibility; real
 * vaults always draw salts and IVs from the platform CSPRNG.
 */
import { Buffer } from 'node:buffer';
import { createCipheriv, createHash, hkdfSync } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { canonicalize } from 'json-canonicalize';

const CRYPTO_PROFILE = 'lexaegis.vault.hkdf-sha256.aes-256-gcm.v1';
const KEY_INFO_DOMAIN = 'lexaegis:vault-object-key:v1';
const AAD_DOMAIN = 'lexaegis:vault-object-aad:v1';

const hex = (bytes) => `0x${Buffer.from(bytes).toString('hex')}`;
const b64url = (bytes) => Buffer.from(bytes).toString('base64url');
const sequence = (start, length) =>
  Buffer.from(Array.from({ length }, (_, index) => (start + index) & 255));
const withDomain = (domain, jcs) =>
  Buffer.concat([Buffer.from(domain, 'utf8'), Buffer.from([0]), Buffer.from(jcs, 'utf8')]);

function seal({ prf, vaultId, objectId, ownerAddress, rpId, salt, iv, plaintext }) {
  const binding = { cryptoProfileId: CRYPTO_PROFILE, vaultId, objectId, ownerAddress, rpId };
  const info = withDomain(KEY_INFO_DOMAIN, canonicalize(binding));
  const header = {
    schema: 'lexaegis.vault-object.v1',
    cryptoProfileId: CRYPTO_PROFILE,
    vaultId,
    objectId,
    ownerAddress,
    rpId,
    hkdfSalt: b64url(salt),
    iv: b64url(iv),
  };
  const aad = withDomain(AAD_DOMAIN, canonicalize(header));
  const key = Buffer.from(hkdfSync('sha256', prf, salt, info, 32));
  const cipher = createCipheriv('aes-256-gcm', key, iv, { authTagLength: 16 });
  cipher.setAAD(aad);
  const ciphertext = Buffer.concat([cipher.update(plaintext), cipher.final(), cipher.getAuthTag()]);
  const envelope = { header, ciphertext: b64url(ciphertext) };
  const wire = Buffer.from(canonicalize(envelope), 'utf8');
  return {
    binding,
    infoHex: hex(info),
    aadHex: hex(aad),
    derivedKeyHex: hex(key),
    ciphertextHex: hex(ciphertext),
    envelope,
    envelopeWireHex: hex(wire),
    envelopeSha256: hex(createHash('sha256').update(wire).digest()),
    envelopeByteLength: String(wire.length),
  };
}

const OWNER = `0x${'22'.repeat(20)}`;
const RP = 'app.lexaegis.test';

const inputs = [
  {
    id: 'structured-json',
    description: 'A small JSON payload',
    prf: sequence(0, 32),
    vaultId: 'b0000000-0000-4000-8000-000000000001',
    objectId: 'b0000000-0000-4000-8000-0000000000a1',
    ownerAddress: OWNER,
    rpId: RP,
    salt: sequence(32, 32),
    iv: sequence(64, 12),
    plaintext: Buffer.from('{"synthetic":true,"note":"vault vector"}', 'utf8'),
  },
  {
    id: 'binary-artifact',
    description: 'Binary bytes including zero, high bytes and CRLF',
    prf: sequence(0, 32),
    vaultId: 'b0000000-0000-4000-8000-000000000001',
    objectId: 'b0000000-0000-4000-8000-0000000000a2',
    ownerAddress: OWNER,
    rpId: RP,
    salt: sequence(100, 32),
    iv: sequence(140, 12),
    plaintext: Buffer.from([0, 1, 2, 13, 10, 0xff, 0xfe, 0x80, 0x7f, 0, 0]),
  },
  {
    id: 'other-prf-other-owner',
    description: 'Another PRF output, owner, vault and rpId with the empty plaintext',
    prf: sequence(200, 32),
    vaultId: 'b0000000-0000-4000-8000-000000000002',
    objectId: 'b0000000-0000-4000-8000-0000000000a3',
    ownerAddress: `0x${'33'.repeat(20)}`,
    rpId: 'localhost',
    salt: sequence(7, 32),
    iv: sequence(9, 12),
    plaintext: Buffer.alloc(0),
  },
].map((item) => ({
  id: item.id,
  description: item.description,
  prfOutput: hex(item.prf),
  hkdfSalt: hex(item.salt),
  iv: hex(item.iv),
  plaintextHex: hex(item.plaintext),
  expected: seal(item),
}));

const vectors = {
  $comment:
    'SYNTHETIC vault crypto vectors. Generated by fixtures/vault-v1/generate.mjs with node:crypto, independently of the application. PRF outputs, salts and IVs are FIXED for testing and must never be used in production. Do not edit by hand.',
  format: 'lexaegis.vault-v1.test-vectors/1',
  cryptoProfile: CRYPTO_PROFILE,
  cases: inputs,
};

const path = join(dirname(fileURLToPath(import.meta.url)), 'vectors.json');
const output = `${JSON.stringify(vectors, null, 2)}\n`;

function readOrNull(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}

if (process.argv.includes('--check')) {
  if (readOrNull(path) !== output) {
    console.error('fixtures/vault-v1/vectors.json is not reproducible from generate.mjs');
    process.exit(1);
  }
  console.log('fixtures/vault-v1/vectors.json is reproducible');
} else {
  writeFileSync(path, output);
  console.log(`wrote ${vectors.cases.length} cases to fixtures/vault-v1/vectors.json`);
}
