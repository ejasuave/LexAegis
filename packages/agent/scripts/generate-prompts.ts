/**
 * Generates (or with --check verifies) the pinned prompt manifest and the embedded prompt module.
 *
 *   prompts/*.md                         -> exact UTF-8 bytes, hashed with SHA-256
 *   output, intent and tool schemas      -> RFC 8785 canonical JSON, hashed with SHA-256
 *   prompts/manifest.v1.json             -> digests, recorded outside the content they describe
 *   src/runtime/generated/prompt-assets.ts -> the same text and digests for the runtime
 *
 * Templates are repository files. Nothing here reads a document, a request or the network.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalizeJson } from '@lexaegis/protocol/v1';
import { assistantIntentSchema, type AssistantIntent } from '../src/contracts';
import {
  intentSelectionOutputSchema,
  modelOutputSchema,
  toProviderSchema,
} from '../src/runtime/model-schemas';
import { TOOL_NAMES, toolManifestEntry } from '../src/runtime/tool-schemas';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const PROMPTS = join(ROOT, 'prompts');
const MANIFEST = join(PROMPTS, 'manifest.v1.json');
const MODULE = join(ROOT, 'src', 'runtime', 'generated', 'prompt-assets.ts');
const MANIFEST_VERSION = '1';
const WORD_LIMIT = 1200;

const sha256 = (bytes: Uint8Array): string =>
  `0x${createHash('sha256').update(bytes).digest('hex')}`;
const words = (text: string): number => text.split(/\s+/).filter((part) => part !== '').length;
const fileName = (intent: AssistantIntent) => `intent-${intent.replaceAll('_', '-')}.md`;

function asset(id: string, file: string) {
  const bytes = readFileSync(join(PROMPTS, file));
  const text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
  return { id, file, text, sha256: sha256(bytes), bytes: bytes.byteLength, words: words(text) };
}

const common = asset('common-policy', 'common-policy.md');
const router = asset('router', 'router.md');
const intents = assistantIntentSchema.options.map((intent) => ({
  intent,
  ...asset(`intent:${intent}`, fileName(intent)),
}));
for (const item of intents) {
  if (common.words + item.words > WORD_LIMIT) {
    throw new Error(`${item.file}: common policy plus this asset exceeds ${WORD_LIMIT} words`);
  }
}

const schema = (id: string, value: unknown) => ({ id, sha256: sha256(canonicalizeJson(value)) });
const output = schema('output', toProviderSchema(modelOutputSchema));
const selection = schema('intent-selection', toProviderSchema(intentSelectionOutputSchema));
const tools = TOOL_NAMES.map((name) => {
  const entry = toolManifestEntry(name);
  return { name, version: entry.version, sha256: sha256(canonicalizeJson(entry)) };
});

const manifest = {
  schema: 'lexaegis.prompt-manifest.v1',
  manifestVersion: MANIFEST_VERSION,
  hash: 'SHA-256 of exact UTF-8 asset bytes; SHA-256 of RFC 8785 canonical JSON for schemas',
  assets: [common, router, ...intents].map(({ id, file, sha256: digest, bytes, words: count }) => ({
    id,
    file,
    sha256: digest,
    bytes,
    words: count,
  })),
  schemas: [output, selection],
  tools,
};
const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;

const moduleText = `// GENERATED by packages/agent/scripts/generate-prompts.ts. Do not edit: run pnpm agent:prompts:generate.
import type { AssistantIntent, AssistantToolName } from '../../contracts';

export interface PromptAsset {
  readonly text: string;
  /** SHA-256 of the exact UTF-8 bytes of the repository asset. */
  readonly sha256: string;
}

export const PROMPT_MANIFEST_VERSION = ${JSON.stringify(MANIFEST_VERSION)};

export const COMMON_POLICY: PromptAsset = ${JSON.stringify({ text: common.text, sha256: common.sha256 }, null, 2)};

export const ROUTER_ASSET: PromptAsset = ${JSON.stringify({ text: router.text, sha256: router.sha256 }, null, 2)};

export const INTENT_ASSETS: Readonly<Record<AssistantIntent, PromptAsset>> = ${JSON.stringify(
  Object.fromEntries(
    intents.map((item) => [item.intent, { text: item.text, sha256: item.sha256 }]),
  ),
  null,
  2,
)};

export const OUTPUT_SCHEMA_SHA256 = ${JSON.stringify(output.sha256)};
export const INTENT_SCHEMA_SHA256 = ${JSON.stringify(selection.sha256)};

export const TOOL_SCHEMA_SHA256: Readonly<Record<AssistantToolName, string>> = ${JSON.stringify(
  Object.fromEntries(tools.map((tool) => [tool.name, tool.sha256])),
  null,
  2,
)};
`;

if (process.argv.includes('--check')) {
  const stale = [
    [MANIFEST, manifestText],
    [MODULE, moduleText],
  ].filter(([path, expected]) => {
    try {
      return readFileSync(path as string, 'utf8') !== expected;
    } catch {
      return true;
    }
  });
  if (stale.length > 0) {
    console.error(`prompt manifest is out of date: ${stale.map(([path]) => path).join(', ')}`);
    process.exit(1);
  }
  console.log('prompt manifest matches the prompt assets and schemas');
} else {
  writeFileSync(MANIFEST, manifestText);
  writeFileSync(MODULE, moduleText);
  console.log(
    `wrote ${manifest.assets.length} assets, ${manifest.schemas.length} schemas, ${tools.length} tools`,
  );
}
