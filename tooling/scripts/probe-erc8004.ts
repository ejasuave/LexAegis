/**
 * pnpm probe:erc8004: read-only availability probe for the ERC-8004 registries on Monad testnet and,
 * separately, Monad mainnet. Loads no key, signs nothing, sends nothing. Writes
 * docs/erc8004-availability.md, docs/evidence/chapter16-erc8004-probe-<date>.json and the validated
 * evidence result, and records features.agentIdentity.availableOnTestnet (never the product flag).
 * Limits: 5 s per call, one transient retry, 32 attempts, 120 s total. No background polling.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { recordEvidence, readState, writeAtomic } from '../src/evidence-writer';
import {
  LIMITS,
  probeAll,
  testnetAvailability,
  type NetworkResult,
  type RegistryResult,
  type Target,
} from '../src/erc8004-probe';
import { ROOT, stamp } from './lib';

/** Dated documentation: CANDIDATE evidence. It is not an observed working deployment. */
export const SOURCES = {
  checkedOn: '2026-10-11',
  documents: [
    {
      url: 'https://docs.monad.xyz/guides/erc-8004',
      note: 'lists Identity 0x8004A169FB4a3325136EB29fA0ceB6D2e539a432 and Reputation 0x8004BAa17C55a88189AE136b182e5fdA19dE9b63 without naming a network or chain ID; Validation Registry "coming soon"; no registration signature shown',
    },
    {
      url: 'https://eips.ethereum.org/EIPS/eip-8004',
      note: 'Status Draft (Standards Track: ERC), created 2025-08-13; register overloads, giveFeedback, getIdentityRegistry and the registration-file format',
    },
    {
      url: 'https://github.com/erc-8004/erc-8004-contracts',
      note: 'README deployment tables list Monad Mainnet and Monad Testnet addresses; the Identity Registry is described as an upgradeable ERC-721; no chain IDs, proxy or implementation addresses',
    },
    {
      url: 'https://docs.monad.xyz/developer-essentials/network-information',
      note: 'mainnet chain ID 143 and public RPC endpoints (including https://rpc.monad.xyz); no testnet entry on that page',
    },
  ],
  repository: {
    commit: 'b9e466c250744a7e06b13dff9d3c2844ed64f825',
    committedAt: '2026-08-15T16:26:49Z',
    abiSha256: {
      'abis/IdentityRegistry.json':
        'cdb8e30f41a56ed53421126dab87551ff2a178b8463646f69f75bc5dc9620564',
      'abis/ReputationRegistry.json':
        '867b7975a5f2f9fee38c4a148a84471b141f4de91409ccc0c6bebe3df4f04001',
    },
  },
} as const;

const TARGETS: readonly { target: Target; url: string }[] = [
  {
    target: {
      network: 'monad-testnet',
      chainId: 10143,
      identityRegistry: '0x8004A818BFB912233c491871b3d84c89A494BD9e',
      reputationRegistry: '0x8004B663056A597Dffe9eCcC1965A193B7388713',
    },
    url: process.env.ERC8004_TESTNET_RPC_URL ?? 'https://testnet-rpc.monad.xyz/',
  },
  {
    target: {
      network: 'monad-mainnet',
      chainId: 143,
      identityRegistry: '0x8004A169FB4a3325136EB29fA0ceB6D2e539a432',
      reputationRegistry: '0x8004BAa17C55a88189AE136b182e5fdA19dE9b63',
    },
    url: process.env.ERC8004_MAINNET_RPC_URL ?? 'https://rpc.monad.xyz/',
  },
];

const row = (result: RegistryResult | null): string =>
  result === null
    ? 'not checked'
    : `**${result.status}** (${result.reasons.join(', ')})${result.version === null ? '' : `; version ${result.version}`}${
        result.implementation === null ? '' : `; implementation ${result.implementation.address}`
      }`;

function section(network: NetworkResult, target: Target): string[] {
  return [
    `### ${network.network} (chain ${String(network.chainId)})`,
    '',
    `- Endpoint (origin only): ${network.endpoint}`,
    `- Probe: **${network.status}**${network.reasons.length === 0 ? '' : ` (${network.reasons.join(', ')})`}`,
    network.checkpoint === null
      ? '- Checkpoint: none (nothing was interpreted)'
      : `- Checkpoint: block ${network.checkpoint.blockNumber}, hash ${network.checkpoint.blockHash} (finalized minus 3)`,
    `- Identity Registry \`${target.identityRegistry}\`: ${row(network.identity)}`,
    `- Reputation Registry \`${target.reputationRegistry}\`: ${row(network.reputation)}`,
    `- Both registries verified and linked: **${String(network.full)}**`,
    '',
  ];
}

const report = await probeAll({ endpoints: TARGETS });
const available = testnetAvailability(report);
const date = new Date().toISOString().slice(0, 10);

const doc = [
  '# ERC-8004 availability on Monad',
  '',
  `Generated by \`pnpm probe:erc8004\` on ${date}. Read-only: eth_chainId, eth_getBlockByNumber, eth_getCode, eth_getStorageAt and eth_call. No key, wallet, signature or transaction. Limits: ${String(LIMITS.callMs)} ms per call, one transient retry, ${String(LIMITS.attempts)} attempts, ${String(LIMITS.runtimeMs / 1000)} s total. This run used ${String(report.attempts)} attempts in ${String(report.durationMs)} ms.`,
  '',
  `**features.agentIdentity.availableOnTestnet = ${JSON.stringify(available)}.** This is a fact about the network, not the product flag; it enables nothing by itself. Mainnet results never establish testnet availability. Reading code is not proof of the implementation's logic: behaviour was checked through the pinned ABI.`,
  '',
  '## Dated source evidence (candidate, not an observed deployment)',
  '',
  `Checked on ${SOURCES.checkedOn}. Repository \`erc-8004/erc-8004-contracts\` at \`${SOURCES.repository.commit}\` (committed ${SOURCES.repository.committedAt}).`,
  '',
  ...SOURCES.documents.map((source) => `- ${source.url}: ${source.note}`),
  '',
  'Pinned ABI files (SHA-256): ' +
    Object.entries(SOURCES.repository.abiSha256)
      .map(([file, hash]) => `\`${file}\` ${hash}`)
      .join('; '),
  '',
  '## Observed results',
  '',
  ...report.networks.flatMap((network) => {
    const entry = TARGETS.find((item) => item.target.network === network.network);
    return entry === undefined ? [] : section(network, entry.target);
  }),
  '## How to read this',
  '',
  '- `verified`: code is present, `getVersion`, ERC-721 support and the known nonexistent-token result decode (Identity), or `getVersion` and a `getIdentityRegistry` that equals the documented Identity Registry (Reputation).',
  '- `absent`: a successful read found no code at that address at that checkpoint only.',
  '- `incompatible`: code is present but the pinned ABI behaviour or the relationship is not.',
  '- `unknown`: an RPC error, timeout, wrong chain or exhausted budget. It is never read as absence.',
  '- An EIP-1967 implementation observation is recorded where supported; a proxy-code hash alone does not certify unchanged logic.',
  '- Registration, a hosted card and feedback are separate steps and have **not** been performed by this probe.',
  '',
].join('\n');
writeFileSync(join(ROOT, 'docs', 'erc8004-availability.md'), doc);
writeFileSync(
  join(ROOT, 'docs', 'evidence', `chapter16-erc8004-probe-${date}.json`),
  `${JSON.stringify({ schema: 'lexaegis.erc8004-probe.v1', date, sources: SOURCES, availableOnTestnet: available, report }, null, 2)}\n`,
);

const failedHard = report.networks.some((network) => network.status === 'unknown');
await recordEvidence({
  root: ROOT,
  results: [
    stamp({
      id: `erc8004-probe-${new Date().toISOString().replace(/\D/g, '').slice(0, 14)}`,
      subject: 'agent-identity',
      command: 'pnpm probe:erc8004',
      evidenceClass: 'live_testnet',
      outcome: available === true ? 'pass' : available === false ? 'fail' : 'unknown',
      reasonCodes: [
        `AVAILABLE_ON_TESTNET_${String(available).toUpperCase()}`,
        ...(failedHard ? ['A_NETWORK_UNKNOWN'] : []),
      ],
      facts: {
        availableOnTestnet: String(available),
        testnetIdentity: report.networks[0]?.identity?.status ?? 'not_checked',
        testnetReputation: report.networks[0]?.reputation?.status ?? 'not_checked',
        mainnetIdentity: report.networks[1]?.identity?.status ?? 'not_checked',
        mainnetReputation: report.networks[1]?.reputation?.status ?? 'not_checked',
        repositoryCommit: SOURCES.repository.commit,
      },
    }),
  ],
});
// features.agentIdentity.availableOnTestnet is recorded beside, never instead of, the product flag.
const state = readState(ROOT);
const features = (state.features ?? {}) as Record<string, unknown>;
await writeAtomic(
  join(ROOT, 'docs', 'build-state.json'),
  JSON.stringify({
    ...readState(ROOT),
    features: {
      ...features,
      agentIdentity: {
        availableOnTestnet: available,
        observedOn: date,
        evidence: `docs/erc8004-availability.md`,
      },
    },
  }),
);
console.log(`availableOnTestnet = ${JSON.stringify(available)} (see docs/erc8004-availability.md)`);
